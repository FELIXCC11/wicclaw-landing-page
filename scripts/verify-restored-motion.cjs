const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||"playwright");
(async()=>{
  const browser=await chromium.launch();
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  await page.goto("http://127.0.0.1:3100/pre-order",{waitUntil:"networkidle"});
  await page.locator("#highlights").scrollIntoViewIfNeeded();
  await page.getByRole("button",{name:"Pause highlights",exact:true}).click();
  await page.getByRole("button",{name:"Show chip performance highlight",exact:true}).click();
  await page.getByRole("button",{name:"Play highlights",exact:true}).click();
  await page.waitForTimeout(500);
  const scale=()=>page.locator(".dots .active span").evaluate(el=>Number(getComputedStyle(el).transform.split("(")[1].split(",")[0]));
  const advancing=await scale();
  assert.ok(advancing>0,"Progress indicator advances during playback");
  await page.getByRole("button",{name:"Pause highlights",exact:true}).click();
  const paused=await scale();await page.waitForTimeout(500);
  assert.ok(Math.abs(await scale()-paused)<.001,"Progress indicator freezes while paused");
  await page.locator("#why-wicclaw").scrollIntoViewIfNeeded();
  await page.getByRole("button",{name:"Next buying benefits"}).click();
  await page.waitForTimeout(700);
  assert.ok(await page.locator(".reasons-track").evaluate(el=>el.scrollLeft)>0);
  await page.getByRole("button",{name:"Previous buying benefits"}).click();
  await page.waitForTimeout(700);
  assert.ok(await page.locator(".reasons-track").evaluate(el=>el.scrollLeft)<2);
  await page.setViewportSize({width:390,height:844});
  await page.goto("http://127.0.0.1:3100/pre-order",{waitUntil:"networkidle"});
  await page.getByRole("button",{name:"Open menu",exact:true}).click();
  await page.locator(".nav-links a").filter({hasText:"Design"}).click();
  await page.waitForTimeout(700);
  assert.equal(await page.locator(".nav-links").isVisible(),false);
  assert.equal(await page.locator("#design").count(),1);
  await page.locator(".local-nav .buy-button").click();
  await page.waitForURL("**/shop/buy-wicclaw");
  assert.equal(await page.getByRole("button",{name:"Add to Bag",exact:true}).count(),1);
  const result={checks:["Progress advances during playback","Progress freezes when paused","Buying carousel forward and reverse","Mobile menu and section navigation","Mobile preorder button reaches product configuration"],passed:true};
  fs.writeFileSync("docs/restoration/motion.json",JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
